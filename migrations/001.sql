-- ============================================================================
-- 1. EXTENSIONES REQUERIDAS
-- ============================================================================
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS unaccent;

-- ============================================================================
-- 2. TIPOS ENUM
-- ============================================================================
CREATE TYPE anime_type_enum AS ENUM ('TV', 'TV_SHORT', 'MOVIE', 'SPECIAL', 'OVA', 'ONA', 'MUSIC', 'UNKNOWN');
CREATE TYPE anime_status_enum AS ENUM ('FINISHED', 'RELEASING', 'NOT_YET_RELEASED', 'CANCELLED', 'HIATUS');
CREATE TYPE anime_source_enum AS ENUM ('ORIGINAL', 'MANGA', 'LIGHT_NOVEL', 'VISUAL_NOVEL', 'VIDEO_GAME', 'OTHER', 'NOVEL', 'DOUJINSHI', 'ANIME', 'WEB_NOVEL', 'LIVE_ACTION', 'GAME', 'COMIC', 'MULTIMEDIA_PROJECT', 'PICTURE_BOOK');
CREATE TYPE season_epoch_enum AS ENUM ('WINTER', 'SPRING', 'SUMMER', 'FALL');

-- ============================================================================
-- 3. TABLAS
-- ============================================================================
CREATE TABLE anime (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Mapea el row_index de Polars
    anime_id         integer UNIQUE,                                       -- ID de AniList
    mal_id           integer UNIQUE,                                       -- ID de MyAnimeList (puede ser NULL)
    score            numeric(5, 2),                                        -- Permite escalas 0-100 (ej. 84.00) o 0-10
    mean_score       numeric(5, 2),
    rank             integer,
    popularity       integer,
    popularity_rank  integer
);

CREATE INDEX idx_anime_score ON anime(score DESC NULLS LAST);
CREATE INDEX idx_anime_popularity_rank ON anime(popularity_rank ASC NULLS LAST);


CREATE TABLE anime_data (
    anime_id           integer PRIMARY KEY REFERENCES anime(anime_id) ON DELETE CASCADE,
    type               anime_type_enum,
    status             anime_status_enum,
    source             anime_source_enum,
    season_epoch       season_epoch_enum,
    season_year        smallint,
    episodes           integer DEFAULT 1,
    duration           integer,
    total_duration     integer GENERATED ALWAYS AS (COALESCE(episodes, 1) * COALESCE(duration, 0)) STORED,
    country_of_origin  varchar(10),
    is_licensed        boolean DEFAULT false,
    is_adult           boolean DEFAULT false,
    start_date         date,
    end_date           date,
    members            integer DEFAULT 0,
    favorites          integer DEFAULT 0,
    watching           integer DEFAULT 0,
    completed          integer DEFAULT 0,
    on_hold            integer DEFAULT 0,
    dropped            integer DEFAULT 0,
    plan_to_watch      integer DEFAULT 0
);

CREATE INDEX idx_anime_data_filters ON anime_data(type, status, season_year, season_epoch) WHERE is_adult = false;


-- ============================================================================
-- 4. TABLA DE BÚSQUEDA (Texto, Trigramas, TSVector y Embeddings)
-- ============================================================================
CREATE TABLE anime_info (
    anime_id               integer PRIMARY KEY REFERENCES anime(id) ON DELETE CASCADE,
    title                  varchar(500) NOT NULL,
    english_title          varchar(500),
    japanese_title         varchar(500),
    user_preferred_title   varchar(500),
    synonyms               text,
    hashtag                varchar(255),
    genres_text            text,
    tags_text              text,
    synopsis               text,
    dense_text             text,
    -- Columna consolidada autogenerada para búsqueda por trigramas (Fuzzy Search en todos los títulos)
    all_titles_search      text GENERATED ALWAYS AS (
        COALESCE(title, '') || ' ' ||
        COALESCE(english_title, '') || ' ' ||
        COALESCE(japanese_title, '') || ' ' ||
        COALESCE(synonyms, '')
    ) STORED,

    -- Columna autogenerada TSVector con pesos (A: Títulos, B: Géneros/Tags, C: Sinopsis)
    search_tsv             tsvector GENERATED ALWAYS AS (
        setweight(to_tsvector('english', COALESCE(title, '')), 'A') ||
        setweight(to_tsvector('english', COALESCE(english_title, '')), 'A') ||
        setweight(to_tsvector('simple',  COALESCE(synonyms, '')), 'B') ||
        setweight(to_tsvector('english', COALESCE(genres_text, '') || ' ' || COALESCE(tags_text, '')), 'B') ||
        setweight(to_tsvector('english', COALESCE(synopsis, '')), 'C')
    ) STORED,

    -- Vector de Embeddings (384 dims para all-MiniLM-L6-v2 / BGE-small, o cambia a 768 / 1024 / 1536 según tu modelo)
    embedding              vector(384)
);

-- Índices de Búsqueda en anime_info
-- 1. Índice GIN para Full-Text Search (TSVector)
CREATE INDEX idx_anime_info_tsv ON anime_info USING GIN (search_tsv);

-- 2. Índices GIN con pg_trgm para similitud léxica y tolerancia a typos
CREATE INDEX idx_anime_info_title_trgm ON anime_info USING GIN (title gin_trgm_ops);
CREATE INDEX idx_anime_info_all_titles_trgm ON anime_info USING GIN (all_titles_search gin_trgm_ops);

-- 3. Índice HNSW para pgvector (Distancia Coseno: vector_cosine_ops, o Producto Interno: vector_ip_ops)
CREATE INDEX idx_anime_info_embedding_hnsw ON anime_info USING hnsw (embedding vector_cosine_ops)
WITH (m = 16, ef_construction = 64);


-- ============================================================================
-- 5. SISTEMA DE GRAFOS (Nodos y Aristas de Similitud Relacional)
-- ============================================================================
CREATE TABLE node_genre (
    genre_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(100) UNIQUE NOT NULL
);

CREATE TABLE node_studio (
    studio_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(150) UNIQUE NOT NULL
);

CREATE TABLE node_staff (
    staff_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(150) UNIQUE NOT NULL
);

CREATE TABLE node_tag (
    tag_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(100) UNIQUE NOT NULL
);

CREATE TABLE node_character (
    character_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         varchar(150) UNIQUE NOT NULL
);

-- Aristas (Apuntando correctamente a anime(anime_id))
CREATE TABLE edge_anime_genre (
    anime_id   integer NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
    genre_id   integer NOT NULL REFERENCES node_genre(genre_id) ON DELETE CASCADE,
    PRIMARY KEY (anime_id, genre_id)
);

CREATE TABLE edge_anime_studio (
    anime_id       integer NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
    studio_id      integer NOT NULL REFERENCES node_studio(studio_id) ON DELETE CASCADE,
    is_main_studio boolean DEFAULT false, -- Aprovecha tu columna main_studios del CSV
    PRIMARY KEY (anime_id, studio_id)
);

CREATE TABLE edge_anime_staff (
    anime_id   integer NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
    staff_id   integer NOT NULL REFERENCES node_staff(staff_id) ON DELETE CASCADE,
    role       varchar(100),
    PRIMARY KEY (anime_id, staff_id)
);

CREATE TABLE edge_anime_tag (
    anime_id   integer NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
    tag_id     integer NOT NULL REFERENCES node_tag(tag_id) ON DELETE CASCADE,
    PRIMARY KEY (anime_id, tag_id)
);

CREATE TABLE edge_anime_character (
    anime_id     integer NOT NULL REFERENCES anime(id) ON DELETE CASCADE,
    character_id integer NOT NULL REFERENCES node_character(character_id) ON DELETE CASCADE,
    PRIMARY KEY (anime_id, character_id)
);

-- Índices inversos para recorrer el grafo rápidamente (Nodo -> Anime)
CREATE INDEX idx_edge_genre_reverse     ON edge_anime_genre(genre_id, anime_id);
CREATE INDEX idx_edge_studio_reverse    ON edge_anime_studio(studio_id, anime_id);
CREATE INDEX idx_edge_staff_reverse     ON edge_anime_staff(staff_id, anime_id);
CREATE INDEX idx_edge_tag_reverse       ON edge_anime_tag(tag_id, anime_id);
CREATE INDEX idx_edge_character_reverse ON edge_anime_character(character_id, anime_id);
